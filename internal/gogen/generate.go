package gogen

import (
	"fmt"
	"go/format"
	"go/types"
	"sort"
	"strings"

	"github.com/kojah/lockdoc/tools/hyrule/internal/compiler"
	"github.com/kojah/lockdoc/tools/hyrule/internal/hostapi"
	"github.com/kojah/lockdoc/tools/hyrule/internal/matchir"
	"github.com/kojah/lockdoc/tools/hyrule/internal/recordgen"
	"github.com/kojah/lockdoc/tools/hyrule/internal/syntax"
)

// Host is the typed Go generation context.
type Host = hostapi.Host

// Header marks outputs owned by this generator.
const Header = "// Code generated by Hyrule; DO NOT EDIT.\n"

type capture struct {
	id  matchir.ValueID
	typ types.Type
}
type emitter struct {
	host         *Host
	bindings     map[string]*syntax.Binding
	captures     map[string]capture
	out          strings.Builder
	rule         string
	serial       int
	cursor       *matchir.Cursor
	graph        *matchir.Graph
	tables       decisionTables
	unions       []*boundUnion
	constructors map[string]*boundVariant
	established  *boundVariant
	constants    map[string]*boundConstant
	records      []*boundRecord
	recordNames  map[string]*boundRecord
}

// Generate validates structural contracts and emits a single ordered dispatcher.
// The caller must type-check the result to validate literals and assignments.
func Generate(h Host, files []*syntax.File) ([]byte, error) {
	h.Imports = map[string]string{}
	program, err := compiler.Collect(files)
	if err != nil {
		return nil, err
	}
	if h.Signature == nil {
		if program.API != nil || len(program.Bindings) != 0 || len(program.Unions) != 0 || program.HasRules() {
			return nil, fmt.Errorf("schema target accepts only records and derivations")
		}
		e := emitter{host: &h}
		if err := e.bindRecords(program.Records); err != nil {
			return nil, err
		}
		body, err := recordgen.Generate(&h, program)
		if err != nil {
			return nil, err
		}
		return renderSource(&h, body)
	}
	native, err := nativeAPI(&h, program.API)
	if err != nil {
		return nil, err
	}
	sig := h.Signature
	e := emitter{host: &h, bindings: program.Bindings, constants: map[string]*boundConstant{}}
	if err := e.bindUnions(program.Unions); err != nil {
		return nil, err
	}
	if err := e.bindRecords(program.Records); err != nil {
		return nil, err
	}
	if native != nil {
		e.bindNativeRecords(native)
	}
	for _, file := range files {
		for _, item := range file.Items {
			if binding := item.Binding; binding != nil {
				if binding.Kind == "const" {
					if err := e.bindConstant(binding); err != nil {
						return nil, err
					}
				} else if _, _, err := e.host.Hook(binding.GoName); err != nil {
					return nil, &syntax.Diagnostic{Position: binding.Position, Message: err.Error()}
				}
			}
		}
	}
	rules, err := program.Expand(func(rule *syntax.Rule) error {
		checker := emitter{host: e.host, bindings: e.bindings, constructors: e.constructors, recordNames: e.recordNames, constants: e.constants, captures: map[string]capture{}, rule: rule.Name}
		return checker.checkPattern(rule.Match, sig.Params().At(0).Type())
	})
	if err != nil {
		return nil, err
	}
	graph, err := e.decisions(rules, sig.Params().At(0).Type())
	if err != nil {
		return nil, err
	}
	// Planning validates every rule, including unreachable leaves. Only emitted
	// leaves contribute imports to the final source.
	e.out.Reset()
	output := h.TypeName(sig.Results().At(0).Type())
	var params []string
	for i := 0; i < sig.Params().Len(); i++ {
		params = append(params, fmt.Sprintf("harg%d %s", i, h.TypeName(sig.Params().At(i).Type())))
	}
	fmt.Fprintf(&e.out, "// %s applies rules in source order; false means no rule matched.\nfunc %s(%s) (%s, bool) {\n",
		h.Function, h.Function, strings.Join(params, ", "), output)
	if record := e.recordFor(sig.Params().At(0).Type()); record != nil {
		if validation := e.validation(record.typ, "harg0"); validation != "" {
			fmt.Fprintf(&e.out, "if !%s { var zero %s; return zero,false }\n", validation, output)
		}
	}
	if err := e.emitDecisions(graph, nil); err != nil {
		return nil, err
	}
	if !decisionReturns(graph) {
		fmt.Fprintf(&e.out, "var zero %s; return zero, false\n", output)
	}
	e.out.WriteString("}\n")
	e.emitValidators()
	derived, err := recordgen.Generate(&h, program)
	if err != nil {
		return nil, err
	}
	e.out.WriteString(derived)
	if native != nil {
		if err := e.emitNativeAPI(native); err != nil {
			return nil, err
		}
	}
	return renderSource(&h, e.out.String())
}

func renderSource(h *Host, body string) ([]byte, error) {
	var source strings.Builder
	source.WriteString(Header)
	fmt.Fprintf(&source, "\npackage %s\n", h.Package.Name())
	used, err := hostapi.UsedQualifiers(body)
	if err != nil {
		return nil, fmt.Errorf("parse generated body: %w", err)
	}
	paths := []string{}
	for path, name := range h.Imports {
		if used[name] {
			paths = append(paths, path)
		}
	}
	sort.Strings(paths)
	for _, path := range paths {
		fmt.Fprintf(&source, "import %s %q\n", h.Imports[path], path)
	}
	source.WriteString(body)
	result, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w", err)
	}
	if strings.Count(string(result), "\n") > 500 {
		return nil, fmt.Errorf("generated file exceeds 500 lines; split the target")
	}
	return result, nil
}

func (e *emitter) fail(x *syntax.Expr, message string) error {
	return &syntax.Diagnostic{Position: x.Position, Rule: e.rule, Message: message}
}
func (e *emitter) binding(x *syntax.Expr, kind string) (string, *types.Signature, error) {
	b := e.bindings[x.Name]
	if b == nil || b.Kind != kind {
		return "", nil, e.fail(x, "expected "+kind+" binding for "+x.Name)
	}
	name, sig, err := e.host.Hook(b.GoName)
	if err != nil {
		return "", nil, e.fail(x, err.Error())
	}
	return name, sig, nil
}
func (e *emitter) value(x *syntax.Expr, kind string) (string, error) {
	return e.valueExpected(x, kind, nil)
}

func (e *emitter) valueExpected(x *syntax.Expr, kind string, expected types.Type) (string, error) {
	if x.Bind != "" {
		return "", e.fail(x, "captures may only be bound in patterns")
	}
	switch x.Kind {
	case syntax.List:
		if kind != "build" {
			return "", e.fail(x, "lists are construction expressions")
		}
		return e.listValue(x, expected)
	case syntax.Update:
		if kind != "build" {
			return "", e.fail(x, "updates are construction expressions")
		}
		return e.updateValue(x)
	case syntax.Variable:
		var c capture
		var ok bool
		name, path, _ := strings.Cut(x.Name, ".")
		c, ok = e.captures[name]
		if !ok {
			return "", e.fail(x, "unbound capture $"+name)
		}
		if path != "" {
			if _, err := e.host.Project(c.typ, strings.Split(path, ".")); err != nil {
				return "", e.fail(x, err.Error())
			}
			return valueName(c.id) + "." + path, nil
		}
		return valueName(c.id), nil
	case syntax.Literal:
		return x.Name, nil
	case syntax.Symbol:
		value, err := e.constant(x)
		if err != nil {
			return "", err
		}
		return value.object.Name(), nil
	case syntax.Call:
		if record := e.recordNames[x.Name]; record != nil {
			if kind != "build" {
				return "", e.fail(x, "record constructors are not guard expressions")
			}
			return e.recordValue(x, record)
		}
		if constructor := e.constructors[x.Name]; constructor != nil {
			if kind != "build" {
				return "", e.fail(x, "union constructors are not guard expressions")
			}
			return e.constructorValue(x, constructor)
		}
		expanded, err := e.forwardingCall(x, kind)
		if err != nil {
			return "", err
		}
		var name string
		var sig *types.Signature
		if expanded != x {
			x = expanded
			name, sig, err = e.host.Hook(x.Name)
		} else {
			name, sig, err = e.binding(x, kind)
		}
		if err != nil {
			return "", err
		}
		if sig.Results().Len() != 1 || sig.Params().Len() != len(x.Args) && !hasNamedArguments(x) {
			return "", e.fail(x, "hook arity mismatch: require one result and one parameter per argument")
		}
		if kind == "guard" && !types.Identical(sig.Results().At(0).Type(), types.Typ[types.Bool]) {
			return "", e.fail(x, "guard must return bool")
		}
		args, err := e.valueArguments(x, sig, kind)
		if err != nil {
			return "", err
		}
		return name + "(" + strings.Join(args, ", ") + ")", nil
	case syntax.Query:
		return "", e.fail(x, "query is only allowed as a rule result or decision arm")
	case syntax.Effects:
		if kind != "build" || expected == nil {
			return "", e.fail(x, "effects requires a typed build context")
		}
		return e.typedValue(x, expected)
	case syntax.Alternation:
		return "", e.fail(x, "or is only allowed in matcher patterns")
	default:
		return "", e.fail(x, "wildcards are only allowed in patterns")
	}
}
