package gogen

import (
	"fmt"
	"go/format"
	"go/types"
	"sort"
	"strings"

	"github.com/kojah/lockdoc/tools/hyrule/internal/syntax"
)

// Header marks outputs owned by this generator.
const Header = "// Code generated by Hyrule; DO NOT EDIT.\n"

type capture struct {
	name string
	typ  types.Type
}
type emitter struct {
	host     *Host
	bindings map[string]*syntax.Binding
	captures map[string]capture
	out      strings.Builder
	rule     string
	serial   int
}

// Generate validates structural contracts and emits a single ordered dispatcher.
// The caller must type-check the result to validate literals and assignments.
func Generate(h Host, files []*syntax.File) ([]byte, error) {
	h.imports = map[string]string{}
	sig := h.Signature
	if sig.Params().Len() < 1 || sig.Params().Len() > 2 || sig.Results().Len() != 2 ||
		!types.Identical(sig.Results().At(1).Type(), types.Typ[types.Bool]) || sig.Variadic() || sig.TypeParams().Len() != 0 {
		return nil, fmt.Errorf("signature must be func(Input[, Host]) (Output, bool)")
	}
	e := emitter{host: &h, bindings: map[string]*syntax.Binding{}}
	rules, err := e.collect(files)
	if err != nil {
		return nil, err
	}
	output := h.typeName(sig.Results().At(0).Type())
	var params, args []string
	for i := 0; i < sig.Params().Len(); i++ {
		name := fmt.Sprintf("harg%d", i)
		params = append(params, name+" "+h.typeName(sig.Params().At(i).Type()))
		args = append(args, name)
	}
	fmt.Fprintf(&e.out, "// %s applies rules in source order; false means no rule matched.\nfunc %s(%s) (%s, bool) {\n",
		h.Function, h.Function, strings.Join(params, ", "), output)
	for i := range rules {
		fmt.Fprintf(&e.out, "if result, ok := hyrule%sRule%d(%s); ok { return result, true }\n", h.Function, i, strings.Join(args, ", "))
	}
	fmt.Fprintf(&e.out, "var zero %s; return zero, false\n}\n", output)
	for i, r := range rules {
		e.rule = r.Name
		e.captures = map[string]capture{}
		fmt.Fprintf(&e.out, "// Rule %s (%s:%d).\nfunc hyrule%sRule%d(%s) (%s, bool) {\nvar zero %s\n",
			r.Name, r.File, r.Line, h.Function, i, strings.Join(params, ", "), output, output)
		if err := e.pattern(r.Match, "harg0", sig.Params().At(0).Type()); err != nil {
			return nil, err
		}
		for _, condition := range r.Guards {
			guard, err := e.value(condition, "guard")
			if err != nil {
				return nil, err
			}
			fmt.Fprintf(&e.out, "if !(%s) { return zero, false }\n", guard)
		}
		build, err := e.value(r.Build, "build")
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&e.out, "_ = zero\nreturn %s, true\n}\n", build)
	}
	var source strings.Builder
	source.WriteString(Header)
	fmt.Fprintf(&source, "package %s\n", h.Package.Name())
	paths := []string{}
	for path := range h.imports {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		fmt.Fprintf(&source, "import %s %q\n", h.imports[path], path)
	}
	source.WriteString(e.out.String())
	result, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w", err)
	}
	if strings.Count(string(result), "\n") > 500 {
		return nil, fmt.Errorf("generated file exceeds 500 lines; split the target")
	}
	return result, nil
}

func (e *emitter) collect(files []*syntax.File) ([]*syntax.Rule, error) {
	var rules []*syntax.Rule
	names := map[string]bool{}
	for _, file := range files {
		for _, item := range file.Items {
			if b := item.Binding; b != nil {
				if e.bindings[b.Name] != nil {
					return nil, &syntax.Diagnostic{Position: b.Position, Message: "duplicate binding " + b.Name}
				}
				if _, _, err := e.host.hook(b.GoName); err != nil {
					return nil, &syntax.Diagnostic{Position: b.Position, Message: err.Error()}
				}
				e.bindings[b.Name] = b
			} else {
				if names[item.Rule.Name] {
					return nil, &syntax.Diagnostic{Position: item.Rule.Position, Message: "duplicate rule " + item.Rule.Name}
				}
				names[item.Rule.Name] = true
				rules = append(rules, item.Rule)
			}
		}
	}
	if len(rules) == 0 {
		return nil, fmt.Errorf("ruleset is empty")
	}

	return rules, nil
}

func (e *emitter) fail(x *syntax.Expr, message string) error {
	return &syntax.Diagnostic{Position: x.Position, Rule: e.rule, Message: message}
}
func (e *emitter) binding(x *syntax.Expr, kind string) (string, *types.Signature, error) {
	b := e.bindings[x.Name]
	if b == nil || b.Kind != kind {
		return "", nil, e.fail(x, "expected "+kind+" binding for "+x.Name)
	}
	name, sig, err := e.host.hook(b.GoName)
	if err != nil {
		return "", nil, e.fail(x, err.Error())
	}
	return name, sig, nil
}
func (e *emitter) bind(x *syntax.Expr, name, value string, t types.Type) error {
	if old, ok := e.captures[name]; ok {
		if !types.Comparable(t) || !types.Identical(old.typ, t) {
			return e.fail(x, "repeated capture requires identical comparable types")
		}
		if !safeEquality(t) {
			return e.fail(x, "repeated capture may contain an interface; use an explicit equality guard")
		}
		fmt.Fprintf(&e.out, "if %s != %s { return zero, false }\n", old.name, value)
	} else {
		e.captures[name] = capture{value, t}
	}
	return nil
}

// Interfaces, including those embedded in comparable aggregates, can panic on ==.
func safeEquality(t types.Type) bool {
	switch t := t.Underlying().(type) {
	case *types.Interface:
		return false
	case *types.Array:
		return safeEquality(t.Elem())
	case *types.Struct:
		for i := 0; i < t.NumFields(); i++ {
			if !safeEquality(t.Field(i).Type()) {
				return false
			}
		}
	}
	return true
}
func (e *emitter) pattern(x *syntax.Expr, value string, t types.Type) error {
	if x.Bind != "" {
		if err := e.bind(x, x.Bind, value, t); err != nil {
			return err
		}
	}
	switch x.Kind {
	case syntax.Wildcard:
		return nil
	case syntax.Variable:
		return e.bind(x, x.Name, value, t)
	case syntax.Literal:
		fmt.Fprintf(&e.out, "if %s != %s { return zero, false }\n", value, x.Name)
		return nil
	case syntax.Call:
		name, sig, err := e.binding(x, "match")
		if err != nil {
			return err
		}
		n := sig.Results().Len()
		if sig.Params().Len() != 1 || n != len(x.Args)+1 || !types.Identical(sig.Results().At(n-1).Type(), types.Typ[types.Bool]) {
			return e.fail(x, "matcher requires one input and one result per pattern argument followed by bool")
		}
		if !types.AssignableTo(t, sig.Params().At(0).Type()) {
			return e.fail(x, "matcher input type mismatch")
		}
		vars := []string{}
		for range n {
			e.serial++
			vars = append(vars, fmt.Sprintf("hv%d", e.serial))
		}
		fmt.Fprintf(&e.out, "%s := %s(%s)\nif !%s { return zero, false }\n", strings.Join(vars, ", "), name, value, vars[n-1])
		for i, arg := range x.Args {
			fmt.Fprintf(&e.out, "_ = %s\n", vars[i])
			if err = e.pattern(arg, vars[i], sig.Results().At(i).Type()); err != nil {
				return err
			}
		}
		return nil
	default:
		return e.fail(x, "invalid pattern")
	}
}
func (e *emitter) value(x *syntax.Expr, kind string) (string, error) {
	if x.Bind != "" {
		return "", e.fail(x, "captures may only be bound in patterns")
	}
	switch x.Kind {
	case syntax.Variable:
		c, ok := e.captures[x.Name]
		if !ok {
			return "", e.fail(x, "unbound capture $"+x.Name)
		}
		return c.name, nil
	case syntax.Literal:
		return x.Name, nil
	case syntax.Call:
		name, sig, err := e.binding(x, kind)
		if err != nil {
			return "", err
		}
		if sig.Params().Len() != len(x.Args) || sig.Results().Len() != 1 {
			return "", e.fail(x, "hook arity mismatch: require one result and one parameter per argument")
		}
		if kind == "guard" && !types.Identical(sig.Results().At(0).Type(), types.Typ[types.Bool]) {
			return "", e.fail(x, "guard must return bool")
		}
		args := []string{}
		for _, arg := range x.Args {
			value, err := e.value(arg, "build")
			if err != nil {
				return "", err
			}
			args = append(args, value)
		}
		return name + "(" + strings.Join(args, ", ") + ")", nil
	default:
		return "", e.fail(x, "wildcards are only allowed in patterns")
	}
}
