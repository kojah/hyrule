package gogen

import (
	"fmt"
	"go/format"
	"go/types"
	"sort"
	"strings"

	"github.com/kojah/lockdoc/tools/hyrule/internal/compiler"
	"github.com/kojah/lockdoc/tools/hyrule/internal/matchir"
	"github.com/kojah/lockdoc/tools/hyrule/internal/syntax"
)

// Header marks outputs owned by this generator.
const Header = "// Code generated by Hyrule; DO NOT EDIT.\n"

type capture struct {
	id  matchir.ValueID
	typ types.Type
}
type emitter struct {
	host         *Host
	bindings     map[string]*syntax.Binding
	captures     map[string]capture
	out          strings.Builder
	rule         string
	serial       int
	cursor       *matchir.Cursor
	graph        *matchir.Graph
	tables       decisionTables
	unions       []*boundUnion
	constructors map[string]*boundVariant
	established  *boundVariant
}

// Generate validates structural contracts and emits a single ordered dispatcher.
// The caller must type-check the result to validate literals and assignments.
func Generate(h Host, files []*syntax.File) ([]byte, error) {
	h.imports = map[string]string{}
	sig := h.Signature
	if sig.Params().Len() < 1 || sig.Params().Len() > 2 || sig.Results().Len() != 2 ||
		!types.Identical(sig.Results().At(1).Type(), types.Typ[types.Bool]) || sig.Variadic() || sig.TypeParams().Len() != 0 {
		return nil, fmt.Errorf("signature must be func(Input[, Host]) (Output, bool)")
	}
	program, err := compiler.Collect(files)
	if err != nil {
		return nil, err
	}
	e := emitter{host: &h, bindings: program.Bindings}
	if err := e.bindUnions(program.Unions); err != nil {
		return nil, err
	}
	for _, file := range files {
		for _, item := range file.Items {
			if binding := item.Binding; binding != nil {
				if _, _, err := e.host.hook(binding.GoName); err != nil {
					return nil, &syntax.Diagnostic{Position: binding.Position, Message: err.Error()}
				}
			}
		}
	}
	rules, err := program.Expand(func(rule *syntax.Rule) error {
		checker := emitter{host: e.host, bindings: e.bindings, constructors: e.constructors, captures: map[string]capture{}, rule: rule.Name}
		return checker.checkPattern(rule.Match, sig.Params().At(0).Type())
	})
	if err != nil {
		return nil, err
	}
	graph, err := e.decisions(rules, sig.Params().At(0).Type())
	if err != nil {
		return nil, err
	}
	// Planning validates every rule, including unreachable leaves. Only emitted
	// leaves contribute imports to the final source.
	h.imports = map[string]string{}
	e.out.Reset()
	output := h.typeName(sig.Results().At(0).Type())
	var params []string
	for i := 0; i < sig.Params().Len(); i++ {
		params = append(params, fmt.Sprintf("harg%d %s", i, h.typeName(sig.Params().At(i).Type())))
	}
	fmt.Fprintf(&e.out, "// %s applies rules in source order; false means no rule matched.\nfunc %s(%s) (%s, bool) {\n",
		h.Function, h.Function, strings.Join(params, ", "), output)
	if err := e.emitDecisions(graph, nil); err != nil {
		return nil, err
	}
	if !decisionReturns(graph) {
		fmt.Fprintf(&e.out, "var zero %s; return zero, false\n", output)
	}
	e.out.WriteString("}\n")
	e.emitValidators()
	var source strings.Builder
	source.WriteString(Header)
	fmt.Fprintf(&source, "package %s\n", h.Package.Name())
	paths := []string{}
	for path := range h.imports {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		fmt.Fprintf(&source, "import %s %q\n", h.imports[path], path)
	}
	source.WriteString(e.out.String())
	result, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w", err)
	}
	if strings.Count(string(result), "\n") > 500 {
		return nil, fmt.Errorf("generated file exceeds 500 lines; split the target")
	}
	return result, nil
}

func (e *emitter) fail(x *syntax.Expr, message string) error {
	return &syntax.Diagnostic{Position: x.Position, Rule: e.rule, Message: message}
}
func (e *emitter) binding(x *syntax.Expr, kind string) (string, *types.Signature, error) {
	b := e.bindings[x.Name]
	if b == nil || b.Kind != kind {
		return "", nil, e.fail(x, "expected "+kind+" binding for "+x.Name)
	}
	name, sig, err := e.host.hook(b.GoName)
	if err != nil {
		return "", nil, e.fail(x, err.Error())
	}
	return name, sig, nil
}
func (e *emitter) value(x *syntax.Expr, kind string) (string, error) {
	if x.Bind != "" {
		return "", e.fail(x, "captures may only be bound in patterns")
	}
	switch x.Kind {
	case syntax.Variable:
		c, ok := e.captures[x.Name]
		if !ok {
			return "", e.fail(x, "unbound capture $"+x.Name)
		}
		return valueName(c.id), nil
	case syntax.Literal:
		return x.Name, nil
	case syntax.Call:
		if constructor := e.constructors[x.Name]; constructor != nil {
			if kind != "build" {
				return "", e.fail(x, "union constructors are not guard expressions")
			}
			return e.constructorValue(x, constructor)
		}
		name, sig, err := e.binding(x, kind)
		if err != nil {
			return "", err
		}
		if sig.Results().Len() != 1 || sig.Params().Len() != len(x.Args) && !hasNamedArguments(x) {
			return "", e.fail(x, "hook arity mismatch: require one result and one parameter per argument")
		}
		if kind == "guard" && !types.Identical(sig.Results().At(0).Type(), types.Typ[types.Bool]) {
			return "", e.fail(x, "guard must return bool")
		}
		args, err := e.valueArguments(x, sig, kind)
		if err != nil {
			return "", err
		}
		return name + "(" + strings.Join(args, ", ") + ")", nil
	case syntax.Query:
		return "", e.fail(x, "query is only allowed as a rule result or decision arm")
	case syntax.Effects:
		return "", e.fail(x, "effects requires a typed build context")
	case syntax.Alternation:
		return "", e.fail(x, "or is only allowed in matcher patterns")
	default:
		return "", e.fail(x, "wildcards are only allowed in patterns")
	}
}
